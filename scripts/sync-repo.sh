#!/usr/bin/env bash
# Usage: scripts/sync-repo.sh [--dry-run] [--apply block,ruleset,settings] <owner/repo>...
# Reports how each repository drifts from the kit; nothing is written unless --apply names the part.
# Caller workflows are only reported: each repository sets its own inputs in them.
set -euo pipefail
cd "$(dirname "$0")/.."

usage() { echo "usage: $0 [--dry-run] [--apply block,ruleset,settings] <owner/repo>..." >&2; exit 2; }

apply=""
repos=()
while [ "$#" -gt 0 ]; do
  case "$1" in
    --dry-run) shift ;;
    --apply) [ "$#" -ge 2 ] || usage; apply="$2"; shift 2 ;;
    -*) usage ;;
    *) repos+=("$1"); shift ;;
  esac
done
[ "${#repos[@]}" -gt 0 ] || usage
for part in ${apply//,/ }; do
  case "$part" in block | ruleset | settings) ;; *) usage ;; esac
done
applies() { [[ ",$apply," == *",$1,"* ]]; }

version="$(cat VERSION)"
block_path=.github/repo-kit.md
import_line="@$block_path"
ruleset_name="$(jq -r .name rulesets/main-develop.json)"
git describe --exact-match --tags HEAD >/dev/null 2>&1 \
  || echo "warning: this checkout is not a release tag; run from main to compare with $version" >&2

# Compares a ruleset with the kit's on the fields the kit sets: GitHub adds ids, links and default parameters.
normalize='
def checks: if .type == "required_status_checks" then .parameters.required_status_checks |= sort_by(.context) else . end;
{enforcement, conditions,
 bypass_actors: ((.bypass_actors // []) | map({actor_id, actor_type, bypass_mode}) | sort_by(.actor_type, .actor_id)),
 rules: ([.rules[] | checks | . as $rule
   | ([$want.rules[] | select(.type == $rule.type)][0].parameters) as $keep
   | {type, parameters: (if $keep == null then .parameters
       else ((.parameters // {}) | with_entries(select(.key as $k | $keep | has($k)))) end)}] | sort_by(.type))}'

contents() { gh api "repos/$repo/contents/$1?ref=develop" 2>/dev/null; }
decode() { jq -r .content | base64 -d; }

put_file() { # branch, path, content, message, sha of the file on develop or empty
  jq -n --arg branch "$1" --arg content "$(printf '%s\n' "$3" | base64 -w0)" --arg message "$4" --arg sha "$5" \
    '{branch: $branch, content: $content, message: $message} + (if $sha != "" then {sha: $sha} else {} end)' \
    | gh api -X PUT "repos/$repo/contents/$2" --input - >/dev/null
}

sync_block() {
  local block_json="" claude_json="" current="" claude="" new_claude="" drift=false
  local kit_block
  kit_block="$(cat claude-block.md)"
  if block_json="$(contents "$block_path")"; then
    current="$(decode <<<"$block_json")"
    if [ "$current" = "$kit_block" ]; then
      echo "  block: up to date ($version)"
    else
      echo "  block: $(grep -oE 'repo-kit:start [^ ]+' <<<"$current" | cut -d' ' -f2 || echo unknown) -> $version"
      drift=true
    fi
  else
    block_json=""
    echo "  block: $block_path missing"
    drift=true
  fi

  if claude_json="$(contents CLAUDE.md)"; then
    claude="$(decode <<<"$claude_json")"
    if grep -qxF "$import_line" <<<"$claude"; then
      echo "  CLAUDE.md: imports $block_path"
    else
      echo "  CLAUDE.md: does not import $block_path"
      drift=true
      if grep -q '<!-- repo-kit:start' <<<"$claude"; then
        new_claude="$(awk -v line="$import_line" '
          /<!-- repo-kit:start/ { print line; skip = 1; next }
          /<!-- repo-kit:end -->/ { skip = 0; next }
          !skip' <<<"$claude")"
      else
        new_claude="$(printf '%s\n\n%s' "$claude" "$import_line")"
      fi
    fi
  else
    claude_json=""
    echo "  CLAUDE.md: not in git, add the line $import_line to the local copy"
  fi

  { $drift && applies block; } || return 0
  local branch="fix/repo-kit-$version" base
  base="$(gh api "repos/$repo/git/ref/heads/develop" | jq -r .object.sha)"
  if ! jq -n --arg ref "refs/heads/$branch" --arg sha "$base" '{ref: $ref, sha: $sha}' \
    | gh api -X POST "repos/$repo/git/refs" --input - >/dev/null 2>&1; then
    echo "  block: cannot create $branch (it may already exist), nothing pushed"
    return 0
  fi
  if [ "$current" != "$kit_block" ]; then
    put_file "$branch" "$block_path" "$kit_block" "Update the shared kit block to $version" \
      "$(jq -r '.sha // empty' <<<"$block_json")"
  fi
  if [ -n "$new_claude" ]; then
    put_file "$branch" CLAUDE.md "$new_claude" "Import the shared kit block in CLAUDE.md" "$(jq -r .sha <<<"$claude_json")"
  fi
  local url
  url="$(jq -n --arg head "$branch" --arg version "$version" '{title: "Update the shared kit block to \($version)", head: $head, base: "develop",
      body: "Generated by `scripts/sync-repo.sh` of Navino16/.github: `.github/repo-kit.md` is a copy of the kit block at \($version), imported by `CLAUDE.md`."}' \
    | gh api -X POST "repos/$repo/pulls" --input - | jq -r '.html_url // empty')"
  echo "  block: pull request opened ${url}"
}

sync_workflows() {
  local template name json current refs diff_out
  for template in templates/workflows/*.yml; do
    name="$(basename "$template")"
    if json="$(contents ".github/workflows/$name")"; then
      current="$(decode <<<"$json")"
      # Renovate moves the kit references: only the rest of the file is compared.
      refs="$(grep -oE 'Navino16/\.github[^@[:space:]]*@[0-9]+\.[0-9]+\.[0-9]+' <<<"$current" | sed 's/.*@//' | sort -u | paste -sd, || true)"
      case "$refs" in "" | "$version") refs="" ;; *) refs=" (references the kit at $refs)" ;; esac
      if diff_out="$(diff -u --label "kit/$name" --label "$repo/$name" "$template" \
        <(sed -E "s#(Navino16/\.github[^@[:space:]]*)@[0-9]+\.[0-9]+\.[0-9]+#\1@$version#g" <<<"$current"))"; then
        echo "  workflows/$name: matches the template$refs"
      else
        echo "  workflows/$name: differs from the template$refs"
        sed 's/^/    /' <<<"$diff_out"
      fi
    else
      echo "  workflows/$name: missing"
    fi
  done
}

sync_ruleset() {
  local list id existing="" desired e2e=() diff_out
  if ! list="$(gh api "repos/$repo/rulesets" 2>/dev/null)"; then
    echo "  ruleset: unavailable (a private repository needs GitHub Pro)"
    return 0
  fi
  id="$(jq -r --arg name "$ruleset_name" '.[] | select(.name == $name) | .id' <<<"$list")"
  if [ -n "$id" ]; then
    existing="$(gh api "repos/$repo/rulesets/$id")"
    jq -e '[.rules[] | select(.type == "required_status_checks") | .parameters.required_status_checks[].context] | index("ci / E2E")' \
      <<<"$existing" >/dev/null && e2e=(--e2e)
  fi
  desired="$(scripts/apply-ruleset.sh --dry-run "${e2e[@]}" "$repo")"
  if [ -z "$existing" ]; then
    echo "  ruleset: $ruleset_name missing"
  elif diff_out="$(diff -u --label kit --label "$repo" \
    <(jq -S --argjson want "$desired" "$normalize" <<<"$desired") \
    <(jq -S --argjson want "$desired" "$normalize" <<<"$existing"))"; then
    echo "  ruleset: matches${e2e:+ (with ci / E2E)}"
    return 0
  else
    echo "  ruleset: differs"
    sed 's/^/    /' <<<"$diff_out"
  fi
  if applies ruleset; then
    scripts/apply-ruleset.sh "${e2e[@]}" "$repo" | sed 's/^/  ruleset: /'
  fi
}

sync_settings() {
  local out
  out="$(scripts/apply-settings.sh --dry-run "$repo")"
  if grep -q 'already matches' <<<"$out"; then
    echo "  settings: match"
    return 0
  fi
  echo "  settings: differ"
  tail -n +2 <<<"$out" | sed 's/^/  /'
  if applies settings; then
    scripts/apply-settings.sh "$repo" | tail -n 1 | sed 's/^/  settings: /'
  fi
}

failed=0
for repo in "${repos[@]}"; do
  echo "== $repo"
  if ! gh api "repos/$repo/git/ref/heads/develop" >/dev/null 2>&1; then
    echo "  error: no develop branch" >&2
    failed=1
    continue
  fi
  # A subshell on either side of || would run without errexit.
  set +e
  (set -e; sync_block; sync_workflows; sync_ruleset; sync_settings)
  status=$?
  set -e
  [ "$status" -eq 0 ] || { echo "  error: $repo stopped on a failure" >&2; failed=1; }
done
exit "$failed"
